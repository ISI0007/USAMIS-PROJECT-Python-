"""Export PostgreSQL DDL from the same SQLAlchemy metadata used by the app."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable
from app.extensions import db
from app import models  # noqa: F401


def schema_sql():
    dialect = postgresql.dialect()
    parts = ['-- USAMIS Layer 4 schema, generated by scripts/export_schema.py',
             '-- Fresh empty databases only. Normal installation uses flask db upgrade.',
             '-- Includes tables, foreign keys, checks and indexes. No records or secrets.',
             '-- ORM supplies Python-side defaults when records are inserted through the app.',
             'BEGIN;']
    for table in db.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ';')
        for index in sorted(table.indexes, key=lambda index: index.name):
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ';')
    parts.append('COMMIT;')
    return '\n'.join(line.rstrip() for line in '\n\n'.join(parts).splitlines()) + '\n'


if __name__ == '__main__':
    target = Path(__file__).resolve().parents[1] / 'schema.sql'
    target.write_text(schema_sql(), encoding='utf-8')
    print(f'Exported {len(db.metadata.tables)} application tables to {target}')
